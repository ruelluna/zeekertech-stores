import { z } from "zod";
import { DistanceMethod, FeeSource, Fulfillment, PaymentMethod, PaymentStatus, PriceMode } from "./enums";

const Peso = z.number().nonnegative();

export const CustomerSnapshot = z.object({
  id: z.uuid().nullable(),
  name: z.string().min(1),
  phone: z.string().regex(/^09\d{9}$/).nullable(),
  facebookId: z.string().nullable(),
});
export type CustomerSnapshot = z.infer<typeof CustomerSnapshot>;

export const AddressSnapshot = z.object({
  barangay: z.string().min(1),
  streetPurok: z.string(),
  landmark: z.string(),
  lat: z.number().min(-90).max(90),
  lng: z.number().min(-180).max(180),
  riderNotes: z.string(),
});
export type AddressSnapshot = z.infer<typeof AddressSnapshot>;

export const FeeBreakdown = z.object({
  baseFee: Peso,
  includedKm: z.number().nonnegative(),
  perKm: Peso,
  roundTo: z.number().positive(),
  surcharge: Peso,
});
export type FeeBreakdown = z.infer<typeof FeeBreakdown>;

export const DeliveryQuote = z.object({
  distanceKm: z.number().nonnegative(),
  distanceMethod: DistanceMethod,
  travelMinutes: z.number().nonnegative().nullable(),
  fee: Peso,
  feeSource: FeeSource,
  breakdown: FeeBreakdown.nullable(),
});
export type DeliveryQuote = z.infer<typeof DeliveryQuote>;

export const ModifierSelection = z.object({
  group: z.string().min(1),
  option: z.string().min(1),
  priceDelta: Peso,
  requiresCooking: z.boolean(),
});
export type ModifierSelection = z.infer<typeof ModifierSelection>;

export const OrderItem = z.object({
  /** Generated by whoever creates the order; availability results refer to it. */
  lineId: z.uuid(),
  sku: z.string().min(1),
  /** Copy of the product name at order time. */
  name: z.string().min(1),
  qty: z.number().int().positive(),
  priceMode: PriceMode,
  /** Null for market-price items until staff confirm the final price. */
  unitPrice: Peso.nullable(),
  estimatedUnitPrice: Peso.nullable(),
  weightKg: z.number().positive().nullable(),
  modifiers: z.array(ModifierSelection),
  notes: z.string(),
  needsAvailability: z.boolean(),
  /** False for frozen "As is" packs: they skip the kitchen queue. */
  requiresCooking: z.boolean(),
  prepMinutes: z.number().int().nonnegative(),
  /** Sub-brand name (e.g. "Sweet Treats by Yang"); null for the main menu. Missing in older payloads. */
  brand: z.string().nullable().default(null),
});
export type OrderItem = z.infer<typeof OrderItem>;

export const Discount = z.object({
  promotionId: z.uuid(),
  code: z.string().nullable(),
  amount: Peso,
});
export type Discount = z.infer<typeof Discount>;

export const PaymentInfo = z.object({
  method: PaymentMethod,
  status: PaymentStatus,
});
export type PaymentInfo = z.infer<typeof PaymentInfo>;

export const Totals = z.object({
  subtotal: Peso,
  discount: Discount.nullable(),
  deliveryFee: Peso,
  /** Estimated while any market-price item is unconfirmed. */
  total: Peso,
  isEstimate: z.boolean(),
});
export type Totals = z.infer<typeof Totals>;

export const WebOrder = z
  .object({
    orderId: z.string().min(1),
    customer: CustomerSnapshot,
    fulfillment: Fulfillment,
    scheduledFor: z.iso.datetime({ offset: true }),
    address: AddressSnapshot.nullable(),
    delivery: DeliveryQuote.nullable(),
    items: z.array(OrderItem).min(1),
    needsAvailability: z.boolean(),
    /** Longest wait to confirm uncertain items (minutes), shown to the customer and used for staff alerts. */
    confirmWaitMinutes: z.number().int().positive().nullable(),
    totals: Totals,
    payment: PaymentInfo,
    /** e.g. possible_duplicate_discount, estimated_distance */
    flags: z.array(z.string()),
  })
  .refine((o) => o.fulfillment === "pickup" || (o.address !== null && o.delivery !== null), {
    message: "Delivery orders need an address and a delivery quote",
    path: ["address"],
  });
export type WebOrder = z.infer<typeof WebOrder>;
